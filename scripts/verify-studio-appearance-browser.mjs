import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import assert from 'node:assert/strict';
import React from 'react';
import { renderToString } from 'react-dom/server';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';
import { chromium } from 'playwright';
const output=path.resolve('.studio-appearance-qa');
await fs.mkdir(output,{recursive:true});
const nextMocks={name:'next-router-fixture',setup(b){
 b.onResolve({filter:/^next\/(navigation|link)$/},args=>({path:args.path,namespace:'mock'}));
 b.onLoad({filter:/.*/,namespace:'mock'},args=>({contents:args.path.endsWith('navigation')?'export const usePathname=()=>"/admin"; export const useRouter=()=>({replace(){},refresh(){}});':'import React from "react"; export default function Link({children,...props}){return React.createElement("a",props,children)}',resolveDir:process.cwd()}));
 b.onLoad({filter:/\.css$/},()=>({contents:'',loader:'js'}));
}};
const common={bundle:true,plugins:[nextMocks],jsx:'automatic',logLevel:'error'};
await build({...common,entryPoints:['scripts/fixtures/studio-appearance.tsx'],platform:'node',format:'cjs',external:['react','react-dom'],outfile:`${output}/fixture.cjs`});
await build({...common,stdin:{contents:'import React from "react"; import {hydrateRoot} from "react-dom/client"; import App from "./scripts/fixtures/studio-appearance"; hydrateRoot(document.getElementById("root"),React.createElement(App));',resolveDir:process.cwd(),loader:'tsx'},platform:'browser',outfile:`${output}/client.js`});
const App=createRequire(import.meta.url)(`${output}/fixture.cjs`).default;
const base=await postcss([tailwind()]).process(await fs.readFile('app/globals.css','utf8'),{from:'app/globals.css'});
const appearance=await postcss([tailwind()]).process(await fs.readFile('app/admin/studio-appearance.css','utf8'),{from:'app/admin/studio-appearance.css'});
const html=`<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><style>${base.css}\n${appearance.css}</style></head><body><div id="root">${renderToString(React.createElement(App))}</div><script src="/client.js"></script></body></html>`;
const server=createServer(async(req,res)=>{
 if(['/fonts/helios.otf','/fonts/heliosbold.ttf','/fonts/heliosbolditalic.ttf'].includes(req.url)){res.setHeader('content-type',req.url.endsWith('.otf')?'font/otf':'font/ttf');res.end(await fs.readFile('public'+req.url));return;}
 res.setHeader('content-type',req.url==='/client.js'?'text/javascript; charset=utf-8':'text/html; charset=utf-8');res.end(req.url==='/client.js'?await fs.readFile(`${output}/client.js`):html)});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? {executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH} : {});
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'light'});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
 const url=`http://127.0.0.1:${server.address().port}`;
 await page.goto(url);await page.evaluate(()=>document.fonts.ready);await page.getByRole('button',{name:'Appearance: System',exact:true}).waitFor();
 const trigger=p=>p.getByRole('button',{name:/^Appearance:/});
 const option=(p,name)=>p.getByRole('menuitemradio',{name,exact:true});
 const choose=async(p,name)=>{await trigger(p).click();await option(p,name).click();};
 const surface=()=>page.locator('.admin-form-scope').first().evaluate(el=>getComputedStyle(el).backgroundColor);
 assert.equal(await surface(),'rgb(244, 244, 243)');
 await choose(page,'Night');assert.equal(await surface(),'rgb(9, 9, 10)');
 await page.reload();assert.equal(await trigger(page).getAttribute('aria-label'),'Appearance: Night');
 assert.equal(await surface(),'rgb(9, 9, 10)');
 await page.screenshot({path:`${output}/night-desktop.png`,fullPage:true,animations:"disabled"});
 await choose(page,'Day');assert.equal(await surface(),'rgb(244, 244, 243)');
 assert.equal(await page.locator('main').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(244, 244, 243)');
 assert.equal(await page.getByLabel('Legacy solid black field').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)');
 assert.notEqual(await page.getByRole('checkbox').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)');
 await page.screenshot({path:`${output}/day-desktop.png`,fullPage:true,animations:"disabled"});
 // Keyboard navigation changes focus, not preference, until activated.
 await trigger(page).focus();await page.keyboard.press('ArrowDown');
 assert.equal(await option(page,'Day').evaluate(el=>el===document.activeElement),true);
 await page.keyboard.press('ArrowDown');
 assert.equal(await option(page,'Night').evaluate(el=>el===document.activeElement),true);
 assert.equal(await option(page,'Day').getAttribute('aria-checked'),'true');
 await page.keyboard.press('Enter');
 assert.equal(await trigger(page).getAttribute('aria-label'),'Appearance: Night');
 assert.equal(await trigger(page).evaluate(el=>el===document.activeElement),true);
 await trigger(page).click();await page.keyboard.press('End');
 assert.equal(await option(page,'System').evaluate(el=>el===document.activeElement),true);
 await page.keyboard.press('Home');
 assert.equal(await option(page,'Day').evaluate(el=>el===document.activeElement),true);
 await page.keyboard.press('Escape');assert.equal(await page.getByRole('menu').count(),0);
 assert.equal(await trigger(page).evaluate(el=>el===document.activeElement),true);
 await trigger(page).click();await page.keyboard.press('Tab');assert.equal(await page.getByRole('menu').count(),0);
 await trigger(page).click();await page.locator('main').click({position:{x:300,y:20}});
 assert.equal(await page.getByRole('menu').count(),0);
 await choose(page,'System');await page.emulateMedia({colorScheme:'dark'});assert.equal(await surface(),'rgb(9, 9, 10)');
 await page.emulateMedia({colorScheme:'light'});assert.equal(await surface(),'rgb(244, 244, 243)');
 const tab=await context.newPage();await tab.goto(url);await choose(tab,'Night');
 await page.waitForFunction(()=>document.querySelector('.admin-form-scope').dataset.studioAppearance==='night');await tab.close();
 await choose(page,'Day');
 await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 await page.screenshot({path:`${output}/day-mobile.png`,fullPage:true,animations:"disabled"});
 assert.ok(await trigger(page).isVisible());
 await trigger(page).click();
 assert.equal(await option(page,'Day').getAttribute('aria-checked'),'true');
 const bounds=await page.getByRole('menu').boundingBox();
 assert.ok(bounds.x>=0&&bounds.y>=0&&bounds.x+bounds.width<=390);
 for(const name of ['Day','Night','System']) assert.ok((await option(page,name).boundingBox()).height>=44);
 await page.screenshot({path:`${output}/appearance-menu-mobile.png`,fullPage:true,animations:'disabled'});
 await option(page,'Night').click();assert.equal(await surface(),'rgb(9, 9, 10)');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 // Bootstrap must also preserve stored Night before hydration can execute.
 const noHydration=await context.newPage();await noHydration.route('**/client.js',r=>r.abort());
 await noHydration.addInitScript(()=>localStorage.setItem('helios-studio-appearance','night'));
 await noHydration.goto(url);assert.equal(await noHydration.locator('.admin-form-scope').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(9, 9, 10)');
 console.log('PASS: hydrated actual shell, persistence/reload, keyboard menu navigation, Escape/Tab/outside dismissal, focus restoration, compact mobile menu touch targets, live system changes, cross-tab storage, mobile drawer, no overflow, no hydration errors, pre-hydration persisted theme.');
} finally {await browser.close();server.close();}
